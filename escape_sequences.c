#include <stdio.h>
int main() {
    char name[50];
    int Roll_no;
    printf("Enter your Name : ");
    scanf("%s",name);
    printf("Enter your Roll number : ");
    scanf("%d",&Roll_no);
    printf("Name: %s\n",name);
    printf("Roll Number: %d\n",Roll_no);
    printf("\tTabbed Line\n");
    printf("\\n New Line\n");
}
